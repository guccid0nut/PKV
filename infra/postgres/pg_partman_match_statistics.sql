-- Project Kongor Wave 3B: PostgreSQL 16+ pg_partman Analytics Archive Kit
-- Target Read-Projection / Archive Tables:
--   * stat."MatchStatistics_AnalyticsArchive"
--   * stat."PlayerStatistics_AnalyticsArchive"
--
-- IMPORTANT ARCHITECTURAL CONSTRAINT (PostgreSQL Partitioning vs EF Core OLTP):
--   Do NOT destructively swap or rename the live OLTP tables
--   stat."MatchStatistics" (referenced by 8 EF Core foreign keys including
--   PlayerStatistics, MatchBans, MatchFrags, MatchPlayerInventories,
--   MatchItemEvents, MatchAbilityEvents) or stat."PlayerStatistics" (106 columns
--   with multiple FKs to MatchStatistics, Accounts, Clans, and child tables).
--   PostgreSQL requires every PRIMARY KEY and UNIQUE constraint on a declarative
--   partitioned table to include all partition key columns ("TimestampRecorded"
--   / "MatchTimestampRecorded"), so foreign keys targeting single-column
--   "MatchID" / "ID" cannot reference a partitioned parent table directly
--   without rewriting all referencing tables and EF Core migrations.
--
--   Therefore, these partitioned tables are APPEND-ONLY MONTHLY READ-PROJECTION
--   AND ARCHIVE PARTITIONS fed incrementally from OLTP via the idempotent
--   stat.sync_match_statistics_analytics_archive(...) backfill function below.
--
-- Activation Policy (Operational Thresholds):
--   Do NOT partition small databases unnecessarily. Activate monthly range
--   partitioning via scripts/ops/configure_pg_partman.ps1 once either:
--     1. stat."MatchStatistics" exceeds 50,000,000 rows, OR
--     2. stat."MatchStatistics" + stat."PlayerStatistics" exceeds 20 GiB on disk.
--
-- Compatibility:
--   * PostgreSQL 16+
--   * Supports BOTH pg_partman 4.x (p_type => 'native') AND pg_partman 5.x+
--     (p_type removed) via pg_proc signature inspection.
--   * Registers daily pg_cron maintenance automatically when pg_cron is
--     installed; otherwise emits explicit external scheduler guidance so child
--     partitions never stall after the initial 3-month premake window.
-- ============================================================================

-- 1. Dedicated schema for pg_partman metadata and maintenance routines
CREATE SCHEMA IF NOT EXISTS partman;

-- 2. Install pg_partman extension when available in the PostgreSQL image
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_available_extensions WHERE name = 'pg_partman') THEN
        CREATE EXTENSION IF NOT EXISTS pg_partman SCHEMA partman;
        RAISE NOTICE '[KONGOR-PARTMAN] Extension pg_partman verified in schema partman.';
    ELSE
        RAISE NOTICE '[KONGOR-PARTMAN] pg_partman extension not installed in this PostgreSQL image; staging native declarative archive partition tables with default partitions only.';
    END IF;
END
$$;

-- 3. Ensure statistics schema exists
CREATE SCHEMA IF NOT EXISTS stat;

-- 4. Native PostgreSQL Declarative Monthly-Partitioned Analytics Archive for MatchStatistics
--    (Append-only read projection of hot query columns + TimestampRecorded partition key;
--     leaves OLTP stat."MatchStatistics" and all 8 EF Core foreign keys untouched.)
CREATE TABLE IF NOT EXISTS stat."MatchStatistics_AnalyticsArchive" (
    "ID"                    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    "MatchID"               INTEGER NOT NULL,
    "TimestampRecorded"     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "ServerID"              INTEGER NOT NULL DEFAULT 0,
    "HostAccountName"       VARCHAR(15) NOT NULL DEFAULT '',
    "Map"                   VARCHAR(100) NOT NULL DEFAULT 'caldavar',
    "MapVersion"            VARCHAR(15) NOT NULL DEFAULT '1.0',
    "TimePlayed"            INTEGER NOT NULL DEFAULT 0,
    "GameMode"              VARCHAR(50) NOT NULL DEFAULT 'picking',
    "AveragePSR"            INTEGER NOT NULL DEFAULT 1500,
    "AveragePSRTeamOne"     INTEGER NOT NULL DEFAULT 1500,
    "AveragePSRTeamTwo"     INTEGER NOT NULL DEFAULT 1500,
    "ScoreTeam1"            INTEGER NOT NULL DEFAULT 0,
    "ScoreTeam2"            INTEGER NOT NULL DEFAULT 0,
    "ReleaseStage"          VARCHAR(50) NOT NULL DEFAULT 'RELEASE',
    "ReplayUrl"             VARCHAR(1024),
    "VideoUrl"              VARCHAR(1024),
    PRIMARY KEY ("TimestampRecorded", "MatchID")
) PARTITION BY RANGE ("TimestampRecorded");

-- 5. BRIN + B-Tree Indexes Propagated Automatically to Every Child Monthly Partition
CREATE INDEX IF NOT EXISTS "IX_MatchStatistics_Archive_TimestampRecorded_Brin"
    ON stat."MatchStatistics_AnalyticsArchive" USING BRIN ("TimestampRecorded");

CREATE INDEX IF NOT EXISTS "IX_MatchStatistics_Archive_Map_Ts"
    ON stat."MatchStatistics_AnalyticsArchive" ("Map", "TimestampRecorded" DESC);

CREATE INDEX IF NOT EXISTS "IX_MatchStatistics_Archive_HostAccountName"
    ON stat."MatchStatistics_AnalyticsArchive" ("HostAccountName");

-- 6. Native PostgreSQL Declarative Monthly-Partitioned Analytics Archive for PlayerStatistics
--    (Keyed on MatchTimestampRecorded so joins against MatchStatistics_AnalyticsArchive
--     prune monthly partitions together without mutating 106-column OLTP stat."PlayerStatistics".)
CREATE TABLE IF NOT EXISTS stat."PlayerStatistics_AnalyticsArchive" (
    "ID"                        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    "MatchID"                   INTEGER NOT NULL,
    "MatchTimestampRecorded"    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "AccountID"                 INTEGER NOT NULL,
    "AccountName"               VARCHAR(15) NOT NULL DEFAULT '',
    "HeroIdentifier"            VARCHAR(64) NOT NULL DEFAULT '',
    "Team"                      INTEGER NOT NULL DEFAULT 0,
    "MVP"                       INTEGER NOT NULL DEFAULT 0,
    "Win"                       INTEGER NOT NULL DEFAULT 0,
    "Loss"                      INTEGER NOT NULL DEFAULT 0,
    "HeroKills"                 INTEGER NOT NULL DEFAULT 0,
    "HeroDeaths"                INTEGER NOT NULL DEFAULT 0,
    "HeroAssists"               INTEGER NOT NULL DEFAULT 0,
    "HeroDamage"                INTEGER NOT NULL DEFAULT 0,
    "Actions"                   INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY ("MatchTimestampRecorded", "MatchID", "AccountID")
) PARTITION BY RANGE ("MatchTimestampRecorded");

CREATE INDEX IF NOT EXISTS "IX_PlayerStatistics_Archive_AccountID_Ts"
    ON stat."PlayerStatistics_AnalyticsArchive" ("AccountID", "MatchTimestampRecorded" DESC);

CREATE INDEX IF NOT EXISTS "IX_PlayerStatistics_Archive_AccountID_Hero"
    ON stat."PlayerStatistics_AnalyticsArchive" ("AccountID", "HeroIdentifier");

-- 7. Backwards-compatible read-only alias views (created only when no legacy physical table occupies the name)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'stat'
          AND c.relname = 'MatchStatistics_Partitioned'
          AND c.relkind IN ('r', 'p')
    ) THEN
        EXECUTE 'CREATE OR REPLACE VIEW stat."MatchStatistics_Partitioned" AS SELECT * FROM stat."MatchStatistics_AnalyticsArchive"';
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'stat'
          AND c.relname = 'PlayerStatistics_Partitioned'
          AND c.relkind IN ('r', 'p')
    ) THEN
        EXECUTE 'CREATE OR REPLACE VIEW stat."PlayerStatistics_Partitioned" AS SELECT * FROM stat."PlayerStatistics_AnalyticsArchive"';
    END IF;
END
$$;

-- 8. Idempotent Incremental Backfill / Sync Function (OLTP -> Partitioned Analytics Archive)
--    Safe to execute repeatedly on any time window; uses ON CONFLICT DO NOTHING so existing
--    archived rows are preserved and OLTP tables/foreign keys remain completely untouched.
CREATE OR REPLACE FUNCTION stat.sync_match_statistics_analytics_archive(
    p_since TIMESTAMPTZ DEFAULT NULL,
    p_until TIMESTAMPTZ DEFAULT NULL
)
RETURNS TABLE (
    matches_archived BIGINT,
    player_rows_archived BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_matches BIGINT := 0;
    v_players BIGINT := 0;
BEGIN
    INSERT INTO stat."MatchStatistics_AnalyticsArchive" (
        "MatchID",
        "TimestampRecorded",
        "ServerID",
        "HostAccountName",
        "Map",
        "MapVersion",
        "TimePlayed",
        "GameMode",
        "AveragePSR",
        "AveragePSRTeamOne",
        "AveragePSRTeamTwo",
        "ScoreTeam1",
        "ScoreTeam2",
        "ReleaseStage",
        "ReplayUrl",
        "VideoUrl"
    )
    SELECT
        m."MatchID",
        m."TimestampRecorded",
        m."ServerID",
        m."HostAccountName",
        m."Map",
        m."MapVersion",
        m."TimePlayed",
        m."GameMode",
        m."AveragePSR",
        m."AveragePSRTeamOne",
        m."AveragePSRTeamTwo",
        m."ScoreTeam1",
        m."ScoreTeam2",
        m."ReleaseStage",
        m."ReplayUrl",
        m."VideoUrl"
    FROM stat."MatchStatistics" AS m
    WHERE (p_since IS NULL OR m."TimestampRecorded" >= p_since)
      AND (p_until IS NULL OR m."TimestampRecorded" < p_until)
    ON CONFLICT ("TimestampRecorded", "MatchID") DO NOTHING;

    GET DIAGNOSTICS v_matches = ROW_COUNT;

    INSERT INTO stat."PlayerStatistics_AnalyticsArchive" (
        "MatchID",
        "MatchTimestampRecorded",
        "AccountID",
        "AccountName",
        "HeroIdentifier",
        "Team",
        "MVP",
        "Win",
        "Loss",
        "HeroKills",
        "HeroDeaths",
        "HeroAssists",
        "HeroDamage",
        "Actions"
    )
    SELECT
        p."MatchID",
        m."TimestampRecorded",
        p."AccountID",
        p."AccountName",
        p."HeroIdentifier",
        p."Team",
        p."MVP",
        p."Win",
        p."Loss",
        p."HeroKills",
        p."HeroDeaths",
        p."HeroAssists",
        p."HeroDamage",
        p."Actions"
    FROM stat."PlayerStatistics" AS p
    INNER JOIN stat."MatchStatistics" AS m ON m."MatchID" = p."MatchID"
    WHERE (p_since IS NULL OR m."TimestampRecorded" >= p_since)
      AND (p_until IS NULL OR m."TimestampRecorded" < p_until)
    ON CONFLICT ("MatchTimestampRecorded", "MatchID", "AccountID") DO NOTHING;

    GET DIAGNOSTICS v_players = ROW_COUNT;

    RAISE NOTICE '[KONGOR-PARTMAN] Analytics archive sync complete: matches_archived=%, player_rows_archived=% (window=[%, %)).',
        v_matches, v_players, COALESCE(p_since::TEXT, '-infinity'), COALESCE(p_until::TEXT, '+infinity');

    RETURN QUERY SELECT v_matches, v_players;
END
$$;

-- 9. Register monthly pg_partman lifecycle (premake 3 months ahead, retain 36 months hot)
--    Compatible with BOTH pg_partman 4.x (requires p_type => 'native') and pg_partman 5.x+ (p_type removed).
DO $$
DECLARE
    v_partman_version TEXT;
    v_has_p_type BOOLEAN := FALSE;
    v_has_maint_proc BOOLEAN := FALSE;
    v_target RECORD;
    v_maint_cmd TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_partman') THEN
        SELECT extversion INTO v_partman_version
        FROM pg_extension
        WHERE extname = 'pg_partman';

        SELECT EXISTS (
            SELECT 1
            FROM pg_proc p
            JOIN pg_namespace n ON n.oid = p.pronamespace
            WHERE n.nspname = 'partman'
              AND p.proname = 'create_parent'
              AND 'p_type' = ANY(p.proargnames)
        ) INTO v_has_p_type;

        RAISE NOTICE '[KONGOR-PARTMAN] Detected pg_partman version=% (create_parent has p_type=%).',
            v_partman_version, v_has_p_type;

        FOR v_target IN
            SELECT * FROM (VALUES
                ('stat."MatchStatistics_AnalyticsArchive"', 'TimestampRecorded'),
                ('stat."PlayerStatistics_AnalyticsArchive"', 'MatchTimestampRecorded')
            ) AS t(parent_table, control_col)
        LOOP
            IF NOT EXISTS (
                SELECT 1 FROM partman.part_config WHERE parent_table = v_target.parent_table
            ) THEN
                IF v_has_p_type THEN
                    -- pg_partman 4.x signature (p_type => 'native' required)
                    EXECUTE format(
                        'SELECT partman.create_parent(p_parent_table => %L, p_control => %L, p_type => %L, p_interval => %L, p_premake => %s)',
                        v_target.parent_table,
                        v_target.control_col,
                        'native',
                        '1 month',
                        3
                    );
                ELSE
                    -- pg_partman 5.x+ signature (p_type parameter removed)
                    EXECUTE format(
                        'SELECT partman.create_parent(p_parent_table => %L, p_control => %L, p_interval => %L, p_premake => %s)',
                        v_target.parent_table,
                        v_target.control_col,
                        '1 month',
                        3
                    );
                END IF;

                UPDATE partman.part_config
                   SET retention = '36 months',
                       retention_keep_table = TRUE
                 WHERE parent_table = v_target.parent_table;

                RAISE NOTICE '[KONGOR-PARTMAN] Registered % (control=%, interval=1 month, premake=3, retention=36 months).',
                    v_target.parent_table, v_target.control_col;
            END IF;
        END LOOP;

        -- Automated maintenance registration (CRITICAL: without periodic maintenance, premade partitions stop after 3 months!)
        SELECT EXISTS (
            SELECT 1
            FROM pg_proc p
            JOIN pg_namespace n ON n.oid = p.pronamespace
            WHERE n.nspname = 'partman'
              AND p.proname = 'run_maintenance_proc'
        ) INTO v_has_maint_proc;

        v_maint_cmd := CASE
            WHEN v_has_maint_proc THEN 'CALL partman.run_maintenance_proc();'
            ELSE 'SELECT partman.run_maintenance();'
        END;

        IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
            IF NOT EXISTS (SELECT 1 FROM cron.job WHERE jobname = 'kongor_pg_partman_maintenance') THEN
                EXECUTE format(
                    'SELECT cron.schedule(%L, %L, %L)',
                    'kongor_pg_partman_maintenance',
                    '0 2 * * *',
                    v_maint_cmd
                );
                RAISE NOTICE '[KONGOR-PARTMAN] Scheduled daily pg_cron maintenance job kongor_pg_partman_maintenance (0 2 * * *): %', v_maint_cmd;
            END IF;
        ELSE
            RAISE NOTICE '[KONGOR-PARTMAN] ACTION REQUIRED: pg_cron is not installed. Schedule daily maintenance via external cron/systemd/Kubernetes CronJob or pg_partman_bgw running: %', v_maint_cmd;
        END IF;
    ELSE
        -- Fallback: ensure a default partition exists so archive tables accept rows cleanly without pg_partman
        CREATE TABLE IF NOT EXISTS stat."MatchStatistics_AnalyticsArchive_default"
            PARTITION OF stat."MatchStatistics_AnalyticsArchive" DEFAULT;
        CREATE TABLE IF NOT EXISTS stat."PlayerStatistics_AnalyticsArchive_default"
            PARTITION OF stat."PlayerStatistics_AnalyticsArchive" DEFAULT;
    END IF;
END
$$;

-- 10. Diagnostic Volume View for scripts/ops/configure_pg_partman.ps1 -CheckThresholds
--     Aggregates child partition sizes & row estimates via pg_inherits so partitioned tables
--     (relkind = 'p') never report 0 bytes / 0 rows, AND evaluates the combined
--     MatchStatistics + PlayerStatistics >= 20 GiB threshold explicitly alongside per-table breakdowns.
CREATE OR REPLACE VIEW stat.v_partitioning_threshold_status AS
WITH RECURSIVE target_roots AS (
    SELECT
        c.oid AS root_oid,
        c.relname AS table_name,
        c.relkind AS table_relkind
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'stat'
      AND c.relkind IN ('r', 'p')
      AND c.relname IN (
          'MatchStatistics',
          'PlayerStatistics',
          'MatchStatistics_AnalyticsArchive',
          'PlayerStatistics_AnalyticsArchive'
      )
),
partition_tree AS (
    SELECT
        r.root_oid,
        r.table_name,
        r.table_relkind,
        r.root_oid AS member_oid,
        r.table_relkind AS member_relkind
    FROM target_roots r
    UNION ALL
    SELECT
        pt.root_oid,
        pt.table_name,
        pt.table_relkind,
        child.oid AS member_oid,
        child.relkind AS member_relkind
    FROM partition_tree pt
    JOIN pg_inherits inh ON inh.inhparent = pt.member_oid
    JOIN pg_class child ON child.oid = inh.inhrelid
),
per_table AS (
    SELECT
        pt.table_name,
        pt.table_relkind,
        COUNT(*) FILTER (WHERE pt.member_oid <> pt.root_oid)::BIGINT AS child_partition_count,
        COALESCE(SUM(COALESCE(s.n_live_tup, 0)) FILTER (WHERE pt.member_relkind = 'r'), 0)::BIGINT AS estimated_rows,
        COALESCE(SUM(pg_total_relation_size(pt.member_oid)) FILTER (WHERE pt.member_relkind = 'r'), 0)::BIGINT AS total_bytes
    FROM partition_tree pt
    LEFT JOIN pg_stat_user_tables s ON s.relid = pt.member_oid
    GROUP BY pt.table_name, pt.table_relkind
),
oltp_combined AS (
    SELECT
        COALESCE(MAX(estimated_rows) FILTER (WHERE table_name = 'MatchStatistics'), 0)::BIGINT AS match_stats_rows,
        COALESCE(SUM(estimated_rows) FILTER (WHERE table_name IN ('MatchStatistics', 'PlayerStatistics')), 0)::BIGINT AS combined_oltp_rows,
        COALESCE(SUM(total_bytes) FILTER (WHERE table_name IN ('MatchStatistics', 'PlayerStatistics')), 0)::BIGINT AS combined_oltp_bytes
    FROM per_table
)
SELECT
    pt.table_name,
    CASE WHEN pt.table_relkind = 'p' THEN 'partitioned' ELSE 'heap' END AS storage_kind,
    pt.child_partition_count,
    pt.estimated_rows,
    pt.total_bytes,
    ROUND(pt.total_bytes / (1024.0 * 1024.0 * 1024.0), 3) AS total_gib,
    oc.combined_oltp_bytes,
    ROUND(oc.combined_oltp_bytes / (1024.0 * 1024.0 * 1024.0), 3) AS combined_oltp_gib,
    (
        pt.estimated_rows >= 50000000
        OR pt.total_bytes >= 21474836480
        OR (
            pt.table_name IN ('MatchStatistics', 'PlayerStatistics')
            AND (oc.match_stats_rows >= 50000000 OR oc.combined_oltp_bytes >= 21474836480)
        )
    ) AS partition_recommended
FROM per_table pt
CROSS JOIN oltp_combined oc
UNION ALL
SELECT
    '__COMBINED_OLTP_MATCH_AND_PLAYER__' AS table_name,
    'summary' AS storage_kind,
    0::BIGINT AS child_partition_count,
    oc.combined_oltp_rows AS estimated_rows,
    oc.combined_oltp_bytes AS total_bytes,
    ROUND(oc.combined_oltp_bytes / (1024.0 * 1024.0 * 1024.0), 3) AS total_gib,
    oc.combined_oltp_bytes,
    ROUND(oc.combined_oltp_bytes / (1024.0 * 1024.0 * 1024.0), 3) AS combined_oltp_gib,
    (oc.match_stats_rows >= 50000000 OR oc.combined_oltp_bytes >= 21474836480) AS partition_recommended
FROM oltp_combined oc;
