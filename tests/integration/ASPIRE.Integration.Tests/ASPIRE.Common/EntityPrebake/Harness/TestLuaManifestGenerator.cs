using ASPIRE.Tests.ASPIRE.Common.EntityPrebake.Contracts;
using NLua;

namespace ASPIRE.Tests.ASPIRE.Common.EntityPrebake.Harness;

public sealed class TestLuaManifestGenerator
{
    public string GenerateLuaManifest(EntityCacheContainer container)
    {
        ArgumentNullException.ThrowIfNull(container);

        StringBuilder sb = new();
        sb.AppendLine("-- Generated by Project Kongor Prebake Engine");
        sb.AppendLine($"-- Timestamp: {container.BuildTimestamp}");
        sb.AppendLine($"-- Version: {container.Version}");
        sb.AppendLine();
        sb.AppendLine("HeroDefinitionsCache = {");
        sb.AppendLine("  version = " + container.Version + ",");
        sb.AppendLine("  heroes = {},");
        sb.AppendLine("  alt_avatars = {},");
        sb.AppendLine("  preload_resources = {}");
        sb.AppendLine("}");
        sb.AppendLine();

        foreach (HeroDefinitionDto hero in container.Heroes)
        {
            string heroKey = EscapeLuaString(hero.Name.ToLowerInvariant());
            sb.AppendLine($"HeroDefinitionsCache.heroes[\"{heroKey}\"] = {{");
            sb.AppendLine($"  id = {hero.Id},");
            sb.AppendLine($"  name = \"{EscapeLuaString(hero.Name)}\",");
            sb.AppendLine($"  display_name = \"{EscapeLuaString(hero.DisplayName)}\",");
            sb.AppendLine($"  primary_attribute = \"{EscapeLuaString(hero.PrimaryAttribute)}\",");
            sb.AppendLine($"  icon = \"{EscapeLuaString(hero.IconPath)}\",");
            sb.AppendLine($"  model = \"{EscapeLuaString(hero.ModelPath)}\",");
            sb.AppendLine("  abilities = { " +
                          string.Join(", ", hero.AbilityNames.ConvertAll(a => $"\"{EscapeLuaString(a)}\"")) + " },");
            sb.AppendLine("  alt_avatars = { " +
                          string.Join(", ", hero.AltAvatarKeys.ConvertAll(a => $"\"{EscapeLuaString(a)}\"")) + " }");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        foreach (AltAvatarDto avatar in container.AltAvatars)
        {
            string avatarKey = EscapeLuaString(avatar.Key.ToLowerInvariant());
            string heroKey = EscapeLuaString(avatar.HeroName.ToLowerInvariant());
            sb.AppendLine($"HeroDefinitionsCache.alt_avatars[\"{heroKey}_{avatarKey}\"] = {{");
            sb.AppendLine($"  key = \"{avatarKey}\",");
            sb.AppendLine($"  hero_name = \"{heroKey}\",");
            sb.AppendLine($"  display_name = \"{EscapeLuaString(avatar.DisplayName)}\",");
            sb.AppendLine($"  icon = \"{EscapeLuaString(avatar.IconPath)}\",");
            sb.AppendLine($"  model = \"{EscapeLuaString(avatar.ModelPath)}\",");
            sb.AppendLine($"  priority = {avatar.Priority}");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        return sb.ToString();
    }

    public bool ValidateLuaSyntaxAndExecution(string luaContent, out string? errorMessage)
    {
        try
        {
            using NLua.Lua lua = new();
            lua.DoString(luaContent);
            LuaTable? cacheTable = lua["HeroDefinitionsCache"] as LuaTable;
            if (cacheTable == null)
            {
                errorMessage = "Global table 'HeroDefinitionsCache' was not created.";
                return false;
            }

            errorMessage = null;
            return true;
        }
        catch (Exception ex)
        {
            errorMessage = ex.Message;
            return false;
        }
    }

    public Dictionary<string, object> ExecuteAndExtractHero(string luaContent, string heroName)
    {
        using NLua.Lua lua = new();
        lua.DoString(luaContent);
        string key = heroName.ToLowerInvariant();
        LuaTable? heroTable =
            lua.DoString($"return HeroDefinitionsCache.heroes[\"{EscapeLuaString(key)}\"]")[0] as LuaTable;
        if (heroTable == null) throw new KeyNotFoundException($"Hero '{heroName}' not found in Lua table.");

        Dictionary<string, object> result = new(StringComparer.OrdinalIgnoreCase);
        foreach (object? tableKey in heroTable.Keys)
            if (tableKey != null)
                result[tableKey.ToString()!] = heroTable[tableKey]!;

        return result;
    }

    private static string EscapeLuaString(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "");
    }
}
