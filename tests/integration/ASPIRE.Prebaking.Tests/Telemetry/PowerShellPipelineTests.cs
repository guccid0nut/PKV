using System.Diagnostics;
using ASPIRE.Common.Telemetry;
using ASPIRE.Prebaking.Tests.Infrastructure;
using FluentAssertions;
using Xunit;

namespace ASPIRE.Prebaking.Tests.Telemetry;

[Collection("PowerShellPipeline")]
public sealed class PowerShellPipelineTests
{
    private static string FindRepoRoot()
    {
        DirectoryInfo? current = new(AppContext.BaseDirectory);
        while (current != null)
        {
            if (File.Exists(Path.Combine(current.FullName, "ProjectKongor.slnx"))) return current.FullName;
            current = current.Parent;
        }

        return Directory.GetCurrentDirectory();
    }

    [Fact]
    public void PowerShellPipeline_PrebakeAssetsScript_ExistsAndCompliesWithPowerShellCmdlets()
    {
        // Arrange
        string repoRoot = FindRepoRoot();
        string scriptPath = Path.Combine(repoRoot, "scripts", "prebake-assets.ps1");

        // Assert
        File.Exists(scriptPath).Should().BeTrue($"prebake-assets.ps1 must exist at {scriptPath}");

        string scriptContent = File.ReadAllText(scriptPath);

        // Verify required PowerShell cmdlets and idioms
        scriptContent.Should().Contain("Get-ChildItem");
        scriptContent.Should().Contain("Select-String");
        scriptContent.Should().Contain("ConvertFrom-Json");
        scriptContent.Should().Contain("Format-Table");
        scriptContent.Should().Contain("Test-Path");
        scriptContent.Should().Contain("[PSCustomObject]");
        scriptContent.Should().Contain("PrebakePipelineExecuted");

        // Verify compliance against prohibited Unix commands
        scriptContent.Should().NotContain("grep ");
        scriptContent.Should().NotContain("cp -r");
        scriptContent.Should().NotContain("rm -rf");
    }

    [Trait("Category", "Manual")]
    [Fact]
    public async Task PrebakeAssetsScript_DryRunExecution_ReturnsSuccessWithStructuredOutput()
    {
        if (!NexusTestEnvironment.IsManualTestEnabled) return;

        // Arrange
        string repoRoot = FindRepoRoot();
        string scriptPath = Path.Combine(repoRoot, "scripts", "prebake-assets.ps1");
        File.Exists(scriptPath).Should().BeTrue();

        string tempDir = Path.Combine(Path.GetTempPath(), $"ps_pipeline_test_{Guid.NewGuid():N}");
        Directory.CreateDirectory(tempDir);
        string tempLog = Path.Combine(tempDir, "prebake-telemetry.ndjson");

        try
        {
            // Determine powershell executable (pwsh or powershell.exe)
            string shellExe = OperatingSystem.IsWindows() ? "powershell.exe" : "pwsh";

            ProcessStartInfo psi = new()
            {
                FileName = shellExe,
                Arguments = $"-NoProfile -ExecutionPolicy Bypass -File \"{scriptPath}\" -DryRun -LogFile \"{tempLog}\"",
                WorkingDirectory = repoRoot,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true
            };

            using Process? process = Process.Start(psi);
            process.Should().NotBeNull();

            string stdout = await process!.StandardOutput.ReadToEndAsync();
            string stderr = await process.StandardError.ReadToEndAsync();
            await process.WaitForExitAsync();

            // Assert
            process.ExitCode.Should().Be(0, $"PowerShell script failed with error: {stderr}\nOutput: {stdout}");
            stdout.Should().Contain("SUCCESS");
            stdout.Should().Contain("Pre-Baking Pipeline Status Summary");

            // Verify NDJSON log file output
            File.Exists(tempLog).Should().BeTrue("NDJSON log file should be generated by prebake pipeline");
            IReadOnlyList<EntityTelemetryEvent> events = EntityCacheTelemetryLogger.ReadEventsFromFile(tempLog);
            events.Should().NotBeEmpty();
            events.Should().Contain(e => e.EventName == "PrebakePipelineExecuted" && e.DryRun == true);
        }
        finally
        {
            if (Directory.Exists(tempDir)) Directory.Delete(tempDir, true);
        }
    }
}

