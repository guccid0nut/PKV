<#
.SYNOPSIS
    Audits codebase for deliberate shortcut and technical debt markers.
.DESCRIPTION
    Scans source files (Lua, C++, C#, PS1, XML, Python, JS, etc.) for `shortcut:` (or legacy `ponytail:`)
    comments following the convention: `shortcut: <the ceiling / limit>, <when to upgrade>`.
.PARAMETER Path
    Optional directory or pattern to scan. Defaults to all git-tracked source files plus games/client/override/.
.PARAMETER Marker
    Marker word to search for. Defaults to "shortcut|ponytail".
.PARAMETER OutFile
    Optional file path to write markdown summary to (e.g., docs/SHORTCUT_DEBT.md).
#>
[CmdletBinding()]
param(
    [string]$Path = "",
    [string]$Marker = "shortcut|ponytail",
    [string]$OutFile = ""
)

$ErrorActionPreference = "Stop"

Write-Host "=== Project Kongor: Shortcut & Debt Audit ===" -ForegroundColor Cyan

$sourcePatterns = @('*.lua', '*.ps1', '*.cpp', '*.h', '*.cs', '*.xml', '*.py', '*.js', '*.ts', '*.json', '*.md')

$fileList = @()

if ($Path -and (Test-Path $Path)) {
    Write-Host "Scanning target path: $Path" -ForegroundColor Gray
    $fileList = Get-ChildItem -Path $Path -Recurse -File -Include $sourcePatterns | Select-Object -ExpandProperty FullName
} else {
    Write-Host "Gathering tracked and override source files via git ls-files..." -ForegroundColor Gray
    $repoRootFull = (Get-Location).Path
    $uniquePaths = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
    try {
        $tracked = git --no-optional-locks ls-files -- $sourcePatterns
        foreach ($t in $tracked) {
            if ([string]::IsNullOrWhiteSpace($t)) { continue }
            $fullPath = [System.IO.Path]::GetFullPath((Join-Path $repoRootFull $t))
            if ([System.IO.File]::Exists($fullPath)) {
                [void]$uniquePaths.Add($fullPath)
            }
        }
    } catch {
        # Fallback if git fails
        Get-ChildItem -Path @('scripts', 'games/client/override', 'tools', 'tests', 'docs', '.agents') -Recurse -File -Include $sourcePatterns -ErrorAction SilentlyContinue | ForEach-Object {
            [void]$uniquePaths.Add($_.FullName)
        }
    }

    # Also include any uncommitted override files
    if (Test-Path "games\client\override") {
        Get-ChildItem -Path "games\client\override" -Recurse -File -Include $sourcePatterns -ErrorAction SilentlyContinue | ForEach-Object {
            [void]$uniquePaths.Add($_.FullName)
        }
    }

    $fileList = [string[]][System.Linq.Enumerable]::ToArray($uniquePaths)
}

Write-Host "Scanning $($fileList.Count) candidate files for '${Marker}:' markers..." -ForegroundColor Gray

$pattern = "(?:#|//|--|/\*)\s*(?:$Marker):\s*(?<content>.*)"
$hits = @()

$foundMatches = Select-String -Path $fileList -Pattern $pattern -ErrorAction SilentlyContinue

foreach ($m in $foundMatches) {
    $rawLine = $m.Line.Trim()
    $loc = (Get-Location).Path
    $relPath = if ($m.Path.StartsWith($loc)) { $m.Path.Substring($loc.Length).TrimStart('\', '/') } else { $m.Path }
    
    # Ignore documentation markdown prose referencing shortcut markers in backticks
    if ($relPath.EndsWith(".md") -and $rawLine -match '`[^`]*(?:' + $Marker + '):[^`]*`') {
        continue
    }
    
    # Extract content after marker
    if ($rawLine -match $pattern) {
        $detail = $Matches['content'].Trim().TrimEnd('*/')
    } else {
        $detail = $rawLine
    }
    
    # Split ceiling and trigger if comma exists
    $ceiling = $detail
    $trigger = ""
    if ($detail -match "^(?<ceil>[^,]+),(?<trig>.+)$") {
        $ceiling = $Matches['ceil'].Trim()
        $trigger = $Matches['trig'].Trim()
    }
    
    $hasTrigger = [bool]($trigger.Length -gt 0)
    
    $hits += [PSCustomObject]@{
        File = $relPath
        Line = $m.LineNumber
        Detail = $detail
        Ceiling = $ceiling
        Trigger = if ($hasTrigger) { $trigger } else { "[NO TRIGGER - ROT RISK]" }
        HasTrigger = $hasTrigger
    }
}

if ($hits.Count -eq 0) {
    Write-Host "No shortcut debt markers found. Clean ledger." -ForegroundColor Green
    if ($OutFile) {
        "# Shortcut & Technical Debt Ledger`n`nNo shortcut debt found. Clean ledger.`n" | Set-Content -Path $OutFile -Encoding utf8
    }
    return
}

# Group and display findings
$grouped = $hits | Group-Object -Property File
$noTriggerCount = ($hits | Where-Object { -not $_.HasTrigger }).Count

Write-Host "`nFound $($hits.Count) shortcut marker(s) across $($grouped.Count) file(s) ($noTriggerCount without upgrade trigger):`n" -ForegroundColor Yellow

$mdLines = @()
$mdLines += "# Shortcut & Technical Debt Ledger"
$mdLines += ""
$mdLines += 'Auto-generated by `scripts/qa/audit_debt.ps1`.'
$mdLines += "**Summary:** $($hits.Count) total shortcut marker(s), **$noTriggerCount** rot risk (missing upgrade trigger)."
$mdLines += ""
$mdLines += "| File | Line | Ceiling / Limit | Upgrade Trigger / Path | Status |"
$mdLines += "| :--- | :--- | :--- | :--- | :--- |"

foreach ($g in $grouped) {
    Write-Host "[$($g.Name)]" -ForegroundColor White
    foreach ($item in $g.Group) {
        $color = if ($item.HasTrigger) { "Gray" } else { "Red" }
        $statusStr = if ($item.HasTrigger) { "Tracked" } else { "ROT RISK (No Trigger)" }
        Write-Host "  Line $($item.Line): $($item.Ceiling) | Trigger: $($item.Trigger)" -ForegroundColor $color
        $mdLines += "| ``$($item.File)`` | $($item.Line) | $($item.Ceiling) | $($item.Trigger) | $statusStr |"
    }
}

Write-Host "`nTotal: $($hits.Count) markers, $noTriggerCount with no trigger." -ForegroundColor Cyan

if ($OutFile) {
    $mdLines -join "`n" | Set-Content -Path $OutFile -Encoding utf8
    Write-Host "Exported ledger to $OutFile" -ForegroundColor Green
}
