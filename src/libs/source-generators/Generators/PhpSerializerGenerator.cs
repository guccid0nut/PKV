namespace ASPIRE.SourceGenerator.Generators;

/// <summary>
///     Incremental source generator that generates zero-allocation, compile-time PHP serialization routines
///     for DTO classes and structs annotated with <c>[PhpSerializable]</c>, <c>[PHPProperty]</c>, or <c>[PhpProperty]</c>.
/// </summary>
[Generator]
public class PhpSerializerGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<INamedTypeSymbol> targetSymbols = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is TypeDeclarationSyntax t &&
                                    t.Modifiers.Any(m => m.IsKind(SyntaxKind.PartialKeyword)),
                static (syntaxContext, ct) =>
                {
                    TypeDeclarationSyntax typeDecl = (TypeDeclarationSyntax)syntaxContext.Node;
                    SemanticModel model = syntaxContext.SemanticModel;
                    INamedTypeSymbol? symbol = model.GetDeclaredSymbol(typeDecl, ct);
                    if (symbol is null) return null;

                    bool isTarget = symbol.GetAttributes().Any(IsPhpAttribute) ||
                                    symbol.GetMembers().OfType<IPropertySymbol>()
                                        .Any(p => p.GetAttributes().Any(IsPhpAttribute));

                    return isTarget ? symbol : null;
                })
            .Where(static s => s is not null)!;

        IncrementalValueProvider<ImmutableArray<INamedTypeSymbol>> collectedSymbols = targetSymbols.Collect();

        context.RegisterSourceOutput(collectedSymbols,
            static (sourceContext, symbols) => { Execute(symbols, sourceContext); });
    }

    private static bool IsPhpAttribute(AttributeData a)
    {
        string? name = a.AttributeClass?.Name;
        return name is "PHPPropertyAttribute" or "PhpPropertyAttribute" or "PhpSerializableAttribute";
    }

    private static void Execute(ImmutableArray<INamedTypeSymbol> symbols, SourceProductionContext context)
    {
        HashSet<string> cleanNames = new(StringComparer.OrdinalIgnoreCase);
        HashSet<string> generatedHintNames = new(StringComparer.OrdinalIgnoreCase);

        foreach (INamedTypeSymbol symbol in symbols)
        {
            context.CancellationToken.ThrowIfCancellationRequested();

            string fqName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (!cleanNames.Add(fqName)) continue;

            string generatedSource = GenerateSerializationCode(symbol);
            string cleanName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)
                .Replace("global::", "")
                .Replace(".", "_")
                .Replace("+", "_")
                .Replace("<", "_")
                .Replace(">", "_");
            string baseHint = $"{cleanName}_PhpSerializer.g.cs";
            string hintName = baseHint;
            int counter = 1;
            while (generatedHintNames.Contains(hintName))
            {
                hintName = $"{cleanName}_{counter}_PhpSerializer.g.cs";
                counter++;
            }

            generatedHintNames.Add(hintName);
            context.AddSource(hintName, generatedSource);
        }
    }

    private static string GenerateSerializationCode(INamedTypeSymbol symbol)
    {
        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        string ns = symbol.ContainingNamespace.ToDisplayString();
        sb.AppendLine($"namespace {ns};");
        sb.AppendLine();

        List<INamedTypeSymbol> containingTypes = [];
        INamedTypeSymbol? parent = symbol.ContainingType;
        while (parent != null)
        {
            containingTypes.Insert(0, parent);
            parent = parent.ContainingType;
        }

        foreach (INamedTypeSymbol parentSymbol in containingTypes)
        {
            string parentKind = parentSymbol.IsRecord ? "record" : parentSymbol.IsValueType ? "struct" : "class";
            sb.AppendLine($"public partial {parentKind} {parentSymbol.Name}");
            sb.AppendLine("{");
        }

        string fqTypeName = symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        string typeKind = symbol.IsRecord ? "record" : symbol.IsValueType ? "struct" : "class";

        bool canDeserialize =
            symbol.InstanceConstructors.Any(c =>
                c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public) &&
            !symbol.GetMembers().OfType<IPropertySymbol>().Any(p => p.IsRequired);

        sb.AppendLine(canDeserialize
            ? $"public partial {typeKind} {symbol.Name} : global::ASPIRE.Common.Serialization.PHP.IPhpSerializable, global::ASPIRE.Common.Serialization.PHP.IPhpDeserializable<{fqTypeName}>"
            : $"public partial {typeKind} {symbol.Name} : global::ASPIRE.Common.Serialization.PHP.IPhpSerializable");
        sb.AppendLine("{");

        // Collect readable properties (including inherited base class properties)
        List<PropertyInfoMeta> properties = [];
        HashSet<string> seenPropNames = new(StringComparer.Ordinal);
        INamedTypeSymbol? currentSymbol = symbol;
        while (currentSymbol != null && currentSymbol.SpecialType != SpecialType.System_Object)
        {
            foreach (ISymbol member in currentSymbol.GetMembers())
            {
                if (member is not IPropertySymbol prop || prop.IsStatic || prop.GetMethod is null) continue;

                if (!seenPropNames.Add(prop.Name)) continue;

                bool isIgnored = prop.GetAttributes().Any(a =>
                    a.AttributeClass?.Name is "PhpIgnoreAttribute" or "PHPPropertyIgnoreAttribute"
                        or "JsonIgnoreAttribute");
                if (isIgnored) continue;

                AttributeData? attr = prop.GetAttributes().FirstOrDefault(a =>
                    a.AttributeClass?.Name is "PHPPropertyAttribute" or "PhpPropertyAttribute");

                bool isIntKey = false;
                int intKey = 0;
                string stringKey = prop.Name;
                bool isDiscriminatedUnion = false;

                if (attr is not null && attr.ConstructorArguments.Length > 0)
                {
                    TypedConstant firstArg = attr.ConstructorArguments[0];
                    switch (firstArg.Value)
                    {
                        case int ik:
                            isIntKey = true;
                            intKey = ik;
                            break;
                        case string sk when !string.IsNullOrEmpty(sk):
                            isIntKey = false;
                            stringKey = sk;
                            break;
                        default:
                        {
                            if (firstArg.Value is not null)
                            {
                                string argStr = firstArg.Value.ToString() ?? string.Empty;
                                if (int.TryParse(argStr, out int parsedInt))
                                {
                                    isIntKey = true;
                                    intKey = parsedInt;
                                }
                                else if (!string.IsNullOrEmpty(argStr))
                                {
                                    isIntKey = false;
                                    stringKey = argStr;
                                }
                            }

                            break;
                        }
                    }

                    KeyValuePair<string, TypedConstant> duNamed =
                        attr.NamedArguments.FirstOrDefault(n => n.Key == "IsDiscriminatedUnion");
                    if (duNamed.Key is not null && duNamed.Value.Value is bool duBool) isDiscriminatedUnion = duBool;
                }

                properties.Add(new PropertyInfoMeta
                {
                    Name = prop.Name,
                    IsIntKey = isIntKey,
                    IntKey = intKey,
                    StringKey = stringKey,
                    IsDiscriminatedUnion = isDiscriminatedUnion,
                    TypeSymbol = prop.Type,
                    HasSetter = prop.SetMethod is not null && !prop.SetMethod.IsInitOnly
                });
            }

            currentSymbol = currentSymbol.BaseType;
        }

        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    ///     Zero-allocation PHP serialization routine generated at compile-time.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public void SerializePhp(ref global::ASPIRE.Common.Serialization.PHP.Utf8PhpWriter writer)");
        sb.AppendLine("    {");
        sb.AppendLine($"        writer.WriteArrayHeader({properties.Count});");

        foreach (PropertyInfoMeta prop in properties)
        {
            sb.AppendLine(prop.IsIntKey
                ? $"        writer.WriteKey({prop.IntKey});"
                : $"        writer.WriteKey(\"{prop.StringKey}\");");

            EmitPropertyValueSerialization(sb, prop);
        }

        sb.AppendLine("        writer.WriteArrayFooter();");
        sb.AppendLine("    }");

        if (canDeserialize)
        {
            sb.AppendLine();
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    ///     Zero-allocation PHP deserialization routine generated at compile-time.");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine(
                $"    public static {fqTypeName} DeserializePhp(global::ASPIRE.Common.Serialization.PHP.PhpHashtable table)");
            sb.AppendLine("    {");
            sb.AppendLine($"        {fqTypeName} instance = new {fqTypeName}();");

            foreach (PropertyInfoMeta prop in properties)
            {
                if (!prop.HasSetter) continue;

                string keyExpr = prop.IsIntKey ? prop.IntKey.ToString() : $"\"{prop.StringKey}\"";
                string propTypeFq = prop.TypeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

                if (prop.TypeSymbol.TypeKind == TypeKind.Enum)
                {
                    sb.AppendLine(
                        $"        if (table.TryGetValue({keyExpr}, out object? val_{prop.Name}) && val_{prop.Name} != null)");
                    sb.AppendLine("        {");
                    sb.AppendLine(
                        $"            if (val_{prop.Name} is int intVal_{prop.Name}) instance.{prop.Name} = ({propTypeFq})intVal_{prop.Name};");
                    sb.AppendLine(
                        $"            else if (val_{prop.Name} is string strVal_{prop.Name} && global::System.Enum.TryParse<{propTypeFq}>(strVal_{prop.Name}, true, out {propTypeFq} parsedEnum_{prop.Name})) instance.{prop.Name} = parsedEnum_{prop.Name};");
                }
                else
                {
                    sb.AppendLine(
                        $"        if (table.TryGetValue({keyExpr}, out object? val_{prop.Name}) && val_{prop.Name} is {propTypeFq} typedVal_{prop.Name})");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            instance.{prop.Name} = typedVal_{prop.Name};");
                }

                sb.AppendLine("        }");
            }

            sb.AppendLine("        return instance;");
            sb.AppendLine("    }");
        }

        sb.AppendLine("}");

        for (int i = 0; i < containingTypes.Count; i++) sb.AppendLine("}");

        return sb.ToString();
    }

    private static void EmitPropertyValueSerialization(StringBuilder sb, PropertyInfoMeta prop)
    {
        ITypeSymbol type = prop.TypeSymbol;
        string propExpr = $"this.{prop.Name}";

        if (prop.IsDiscriminatedUnion)
        {
            sb.AppendLine($"        global::ASPIRE.Common.Serialization.PHP.PhpSerializer.SerializeValue(ref writer, {propExpr});");
            return;
        }

        if (type.SpecialType == SpecialType.System_Int32)
        {
            sb.AppendLine($"        writer.WriteInt({propExpr});");
        }
        else if (type.SpecialType == SpecialType.System_Int64)
        {
            sb.AppendLine($"        writer.WriteLong({propExpr});");
        }
        else if (type.SpecialType == SpecialType.System_Boolean)
        {
            sb.AppendLine($"        writer.WriteBool({propExpr});");
        }
        else if (type.SpecialType == SpecialType.System_Double || type.SpecialType == SpecialType.System_Single)
        {
            sb.AppendLine($"        writer.WriteDouble({propExpr});");
        }
        else if (type.SpecialType == SpecialType.System_String)
        {
            sb.AppendLine($"        if ({propExpr} is not null) writer.WriteString({propExpr}); else writer.WriteNull();");
        }
        else if (type.TypeKind == TypeKind.Enum)
        {
            sb.AppendLine($"        writer.WriteInt((int){propExpr});");
        }
        else if (type.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T &&
                 type is INamedTypeSymbol nullableNamed && nullableNamed.TypeArguments.Length == 1)
        {
            ITypeSymbol inner = nullableNamed.TypeArguments[0];
            if (inner.SpecialType == SpecialType.System_Int32)
            {
                sb.AppendLine($"        if ({propExpr}.HasValue) writer.WriteInt({propExpr}.Value); else writer.WriteNull();");
            }
            else if (inner.SpecialType == SpecialType.System_Int64)
            {
                sb.AppendLine($"        if ({propExpr}.HasValue) writer.WriteLong({propExpr}.Value); else writer.WriteNull();");
            }
            else if (inner.SpecialType == SpecialType.System_Boolean)
            {
                sb.AppendLine($"        if ({propExpr}.HasValue) writer.WriteBool({propExpr}.Value); else writer.WriteNull();");
            }
            else if (inner.SpecialType == SpecialType.System_Double || inner.SpecialType == SpecialType.System_Single)
            {
                sb.AppendLine($"        if ({propExpr}.HasValue) writer.WriteDouble({propExpr}.Value); else writer.WriteNull();");
            }
            else if (inner.TypeKind == TypeKind.Enum)
            {
                sb.AppendLine($"        if ({propExpr}.HasValue) writer.WriteInt((int){propExpr}.Value); else writer.WriteNull();");
            }
            else
            {
                sb.AppendLine($"        global::ASPIRE.Common.Serialization.PHP.PhpSerializer.SerializeValue(ref writer, {propExpr});");
            }
        }
        else if (type is IArrayTypeSymbol arrayType && arrayType.ElementType.SpecialType == SpecialType.System_String)
        {
            sb.AppendLine($"        if ({propExpr} is not null)");
            sb.AppendLine("        {");
            sb.AppendLine($"            writer.WriteArrayHeader({propExpr}.Length);");
            sb.AppendLine($"            for (int i = 0; i < {propExpr}.Length; i++)");
            sb.AppendLine("            {");
            sb.AppendLine("                writer.WriteKey(i);");
            sb.AppendLine($"                if ({propExpr}[i] is not null) writer.WriteString({propExpr}[i]); else writer.WriteNull();");
            sb.AppendLine("            }");
            sb.AppendLine("            writer.WriteArrayFooter();");
            sb.AppendLine("        }");
            sb.AppendLine("        else { writer.WriteNull(); }");
        }
        else if (type is INamedTypeSymbol listType && listType.Name == "List" && listType.TypeArguments.Length == 1 &&
                 listType.TypeArguments[0].SpecialType == SpecialType.System_String)
        {
            sb.AppendLine($"        if ({propExpr} is not null)");
            sb.AppendLine("        {");
            sb.AppendLine($"            writer.WriteArrayHeader({propExpr}.Count);");
            sb.AppendLine($"            for (int i = 0; i < {propExpr}.Count; i++)");
            sb.AppendLine("            {");
            sb.AppendLine("                writer.WriteKey(i);");
            sb.AppendLine($"                if ({propExpr}[i] is not null) writer.WriteString({propExpr}[i]); else writer.WriteNull();");
            sb.AppendLine("            }");
            sb.AppendLine("            writer.WriteArrayFooter();");
            sb.AppendLine("        }");
            sb.AppendLine("        else { writer.WriteNull(); }");
        }
        else if (type.AllInterfaces.Any(i => i.Name == "IPhpSerializable") ||
                 type.GetAttributes().Any(IsPhpAttribute))
        {
            sb.AppendLine($"        if ({propExpr} is not null) {propExpr}.SerializePhp(ref writer); else writer.WriteNull();");
        }
        else
        {
            sb.AppendLine($"        global::ASPIRE.Common.Serialization.PHP.PhpSerializer.SerializeValue(ref writer, {propExpr});");
        }
    }

    // ReSharper disable UnusedAutoPropertyAccessor.Local
    private sealed class PropertyInfoMeta
    {
        public string Name { get; set; } = string.Empty;
        public bool IsIntKey { get; set; }
        public int IntKey { get; set; }
        public string StringKey { get; set; } = string.Empty;
        public bool IsDiscriminatedUnion { get; set; }
        public ITypeSymbol TypeSymbol { get; set; } = null!;
        public bool HasSetter { get; set; }
    }
}
