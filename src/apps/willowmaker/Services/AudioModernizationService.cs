    /// <summary>
    ///     Plays or loops the selected audition sound track or in-game effect at the target azimuth angle and distance.
    /// </summary>
    public void PlayAuditionTrack(
        string trackName,
        float azimuthDegrees,
        float distance = 1.0f,
        bool isContinuous = false,
        SpatialAudioOptions? options = null)
    {
        try
        {
            _logger.LogInformation("[SpatialAudio] Playing audition track '{Track}' at {Azimuth}° (Dist: {Dist:F2}, Continuous: {Continuous}, Profile: {Profile}, Channels: {Ch})",
                trackName, azimuthDegrees, distance, isContinuous, options?.HrtfProfile ?? "default", options?.Channels ?? 128);

            SpatialAudioOptions opt = options ?? new SpatialAudioOptions();

            if (isContinuous)
            {
                BinauralSpatialAudioSynthesizer.StartContinuousStream(trackName, azimuthDegrees, distance, opt);
                return;
            }

            byte[] wavBytes;

            if (trackName.Contains("Heart", StringComparison.OrdinalIgnoreCase) ||
                trackName.Contains("Song", StringComparison.OrdinalIgnoreCase))
            {
                wavBytes = BinauralSpatialAudioSynthesizer.GenerateCanYouFeelMyHeartWav(azimuthDegrees, distance, options);
                BinauralSpatialAudioSynthesizer.PlayWavBytes(wavBytes, loop: false);
            }
            else if (trackName.Contains("Orbit", StringComparison.OrdinalIgnoreCase))
            {
                BinauralSpatialAudioSynthesizer.Play3DOrbitSweep(options);
            }
            else if (trackName.Contains("Spell", StringComparison.OrdinalIgnoreCase) ||
                     trackName.Contains("Pyromancer", StringComparison.OrdinalIgnoreCase) ||
                     trackName.Contains("Cast", StringComparison.OrdinalIgnoreCase))
            {
                wavBytes = BinauralSpatialAudioSynthesizer.GenerateSpellCastWav(azimuthDegrees, distance, options);
                BinauralSpatialAudioSynthesizer.PlayWavBytes(wavBytes, loop: false);
            }
            else if (trackName.Contains("Attack", StringComparison.OrdinalIgnoreCase) ||
                     trackName.Contains("Hammerstorm", StringComparison.OrdinalIgnoreCase) ||
                     trackName.Contains("Cleave", StringComparison.OrdinalIgnoreCase))
            {
                wavBytes = BinauralSpatialAudioSynthesizer.GenerateMeleeAttackWav(azimuthDegrees, distance, options);
                BinauralSpatialAudioSynthesizer.PlayWavBytes(wavBytes, loop: false);
            }
            else if (trackName.Contains("Kongor", StringComparison.OrdinalIgnoreCase))
            {
                wavBytes = BinauralSpatialAudioSynthesizer.GenerateAnnouncerWav("kongor_slain", azimuthDegrees, distance, options);
                BinauralSpatialAudioSynthesizer.PlayWavBytes(wavBytes, loop: false);
            }
            else
            {
                wavBytes = BinauralSpatialAudioSynthesizer.GenerateDirectionalWav(azimuthDegrees, distance, options);
                BinauralSpatialAudioSynthesizer.PlayWavBytes(wavBytes, loop: false);
            }
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "[SpatialAudio] Failed to play audition track {Track}", trackName);
        }
    }

