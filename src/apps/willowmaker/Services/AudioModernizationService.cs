/// <summary>
///     Binaural HRTF profiles supported by the Spatial Audio Modernization runtime.
/// </summary>
public enum SpatialHrtfPreset
{
    BuiltInKemar = 0,
    CompetitivePinpoint = 1,
    CinematicWideStage = 2,
    CustomSofa = 3
}

/// <summary>
///     Service responsible for deploying, configuring, and tuning the OpenAL Soft binaural HRTF
///     spatialization pipeline, custom SOFA ear profile scanning, and K2 engine audio cvars.
/// </summary>
public sealed class AudioModernizationService(ILogger<AudioModernizationService> logger)
{
    public const string BuiltInKemarName = "Built-In 48000hz";
    public const string CompetitivePinpointName = "Competitive Pinpoint 48kHz";
    public const string CinematicWideStageName = "Cinematic Wide Stage 48kHz";
    public const string AlsoftConfigFileName = "alsoft.ini";
    public const string HrtfSubdirectory = "hrtf";

    private readonly ILogger<AudioModernizationService> _logger = logger;

    /// <summary>
    ///     Resolves the OS-appropriate OpenAL Soft backend driver list.
    /// </summary>
    public static string ResolveOpenAlDrivers(OSPlatform? platformOverride = null)
    {
        if (platformOverride.HasValue)
        {
            if (platformOverride.Value == OSPlatform.Windows) return "wasapi";
            if (platformOverride.Value == OSPlatform.Linux) return "pulse,alsa";
            if (platformOverride.Value == OSPlatform.OSX) return "core";
        }

        if (OperatingSystem.IsWindows()) return "wasapi";
        if (OperatingSystem.IsLinux()) return "pulse,alsa";
        if (OperatingSystem.IsMacOS()) return "core";
        return "wasapi";
    }

    /// <summary>
    ///     Generates the optimized <c>alsoft.ini</c> configuration content for OpenAL Soft.
    /// </summary>
    public string GenerateAlsoftConfig(
        bool enableHrtf,
        string hrtfProfileName,
        bool enableOcclusionDamping = true,
        int frequency = 48000,
        string? customSofaSearchPath = null,
        OSPlatform? platformOverride = null)
    {
        string hrtfSetting = enableHrtf ? "true" : "false";
        string cleanProfileName = string.IsNullOrWhiteSpace(hrtfProfileName) ? BuiltInKemarName : hrtfProfileName;
        string drivers = ResolveOpenAlDrivers(platformOverride);
        _logger.LogDebug(
            "[AudioModernizationService] Generating alsoft.ini (Drivers={Drivers}, HRTF={HrtfSetting}, Profile={Profile}, Frequency={Frequency})",
            drivers,
            hrtfSetting,
            cleanProfileName,
            frequency);

        // Resolve search paths for custom SOFA or MHR datasets
        string userHrtfDir = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
            "ProjectKongor",
            HrtfSubdirectory).Replace('\\', '/');

        StringBuilder pathsBuilder = new();
        pathsBuilder.Append(userHrtfDir);
        pathsBuilder.Append(", ./").Append(HrtfSubdirectory);
        if (!string.IsNullOrWhiteSpace(customSofaSearchPath))
        {
            pathsBuilder.Append(", ").Append(customSofaSearchPath.Replace('\\', '/'));
        }

        string occlusionGain = enableOcclusionDamping ? "0.25" : "1.0";

        return $"""
                # OpenAL Soft Configuration for Heroes of Newerth (K2 Engine Modernization)
                # Auto-generated by WILLOWMAKER AudioModernizationService
                
                [general]
                drivers = {drivers}
                channels = stereo
                sample-type = float32
                frequency = {frequency}
                stereo-mode = headphones
                stereo-encoding = hrtf
                hrtf = {hrtfSetting}
                hrtf-mode = full
                default-hrtf = {cleanProfileName}
                hrtf-paths = {pathsBuilder}
                resampler = cubic
                cf_level = 0
                sources = 256
                slots = 16
                
                [reverb]
                boost = 0.0
                
                [efx]
                air-absorption-factor = 1.2
                occlusion-gain = {occlusionGain}
                rolloff-factor = 1.0
                """;
    }

    /// <summary>
    ///     Discovers all available HRTF profiles, including built-in presets and any user-provided
    ///     SOFA (.sofa) or OpenAL MHR (.mhr) acoustic files located in client or AppData folders.
    /// </summary>
    public IReadOnlyList<string> DiscoverAvailableProfiles(string? clientRoot = null)
    {
        List<string> profiles =
        [
            BuiltInKemarName,
            CompetitivePinpointName,
            CinematicWideStageName
        ];

        HashSet<string> seen = new(profiles, StringComparer.OrdinalIgnoreCase);

        // 1. Scan client local ./hrtf/ folder
        if (!string.IsNullOrWhiteSpace(clientRoot) && Directory.Exists(clientRoot))
        {
            string localHrtf = Path.Combine(clientRoot, HrtfSubdirectory);
            ScanDirectoryForHrtfFiles(localHrtf, profiles, seen);
        }

        // 2. Scan %APPDATA%/ProjectKongor/hrtf/
        string appDataHrtf = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
            "ProjectKongor",
            HrtfSubdirectory);
        ScanDirectoryForHrtfFiles(appDataHrtf, profiles, seen);

        return profiles;
    }

    private void ScanDirectoryForHrtfFiles(string directoryPath, List<string> profiles, HashSet<string> seen)
    {
        if (!Directory.Exists(directoryPath)) return;

        try
        {
            string[] files = Directory.GetFiles(directoryPath, "*.*", SearchOption.TopDirectoryOnly);
            foreach (string file in files)
            {
                string ext = Path.GetExtension(file);
                if (string.Equals(ext, ".sofa", StringComparison.OrdinalIgnoreCase) ||
                    string.Equals(ext, ".mhr", StringComparison.OrdinalIgnoreCase))
                {
                    string profileName = Path.GetFileName(file);
                    if (seen.Add(profileName))
                    {
                        profiles.Add(profileName);
                        _logger.LogInformation("[SpatialAudio] Discovered custom ear-print profile: {Profile}", profileName);
                    }
                }
            }
        }
        catch (Exception ex)
        {
            _logger.LogWarning(ex, "[SpatialAudio] Error scanning directory {Path} for HRTF files", directoryPath);
        }
    }

