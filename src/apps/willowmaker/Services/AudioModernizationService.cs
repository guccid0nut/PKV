    /// <summary>
    ///     AOT-safe WASAPI default output endpoint sample-rate probe using raw COM vtable dispatch.
    ///     Returns <c>44100</c> if the active Windows output device operates natively at 44.1 kHz,
    ///     or <c>48000</c> otherwise (preventing sample-rate mismatch crackle or buffer underruns).
    /// </summary>
    public static int ProbeDefaultOutputEndpointSampleRate(int? sampleRateOverride = null)
    {
        if (sampleRateOverride.HasValue)
        {
            return sampleRateOverride.Value == 44100 ? 44100 : 48000;
        }

        if (!OperatingSystem.IsWindows())
        {
            return 48000;
        }

        bool comInitialized = false;
        IntPtr pEnumerator = IntPtr.Zero;
        IntPtr pDevice = IntPtr.Zero;
        IntPtr pAudioClient = IntPtr.Zero;
        IntPtr pMixFormat = IntPtr.Zero;

        try
        {
            const uint COINIT_MULTITHREADED = 0x0;
            int hrInit = CoInitializeEx(IntPtr.Zero, COINIT_MULTITHREADED);
            if (hrInit == 0 || hrInit == 1)
            {
                comInitialized = true;
            }

            Guid clsidEnumerator = new("BCDE0395-E52F-467C-8E3D-C4579291692E");
            Guid iidEnumerator = new("A95664D2-9614-4F35-A746-DE8DB63617E6");
            const uint CLSCTX_ALL = 0x17;

            int hrEnum = CoCreateInstance(ref clsidEnumerator, IntPtr.Zero, CLSCTX_ALL, ref iidEnumerator, out pEnumerator);
            if (hrEnum < 0 || pEnumerator == IntPtr.Zero)
            {
                return 48000;
            }

            // IMMDeviceEnumerator::GetDefaultAudioEndpoint is vtable slot 4 (eRender = 0, eMultimedia = 1)
            IntPtr enumVtbl = Marshal.ReadIntPtr(pEnumerator);
            IntPtr pfnGetDefault = Marshal.ReadIntPtr(enumVtbl, 4 * IntPtr.Size);
            GetDefaultAudioEndpointDelegate getDefaultEndpoint =
                Marshal.GetDelegateForFunctionPointer<GetDefaultAudioEndpointDelegate>(pfnGetDefault);

            int hrDevice = getDefaultEndpoint(pEnumerator, 0, 1, out pDevice);
            if (hrDevice < 0 || pDevice == IntPtr.Zero)
            {
                return 48000;
            }

            // IMMDevice::Activate is vtable slot 3
            IntPtr deviceVtbl = Marshal.ReadIntPtr(pDevice);
            IntPtr pfnActivate = Marshal.ReadIntPtr(deviceVtbl, 3 * IntPtr.Size);
            ImmDeviceActivateDelegate activateDevice =
                Marshal.GetDelegateForFunctionPointer<ImmDeviceActivateDelegate>(pfnActivate);

            Guid iidAudioClient = new("1CB9AD4C-DBFA-4c32-B178-C2F568A703B2");
            int hrActivate = activateDevice(pDevice, ref iidAudioClient, CLSCTX_ALL, IntPtr.Zero, out pAudioClient);
            if (hrActivate < 0 || pAudioClient == IntPtr.Zero)
            {
                return 48000;
            }

            // IAudioClient::GetMixFormat is vtable slot 8
            IntPtr clientVtbl = Marshal.ReadIntPtr(pAudioClient);
            IntPtr pfnGetMixFormat = Marshal.ReadIntPtr(clientVtbl, 8 * IntPtr.Size);
            AudioClientGetMixFormatDelegate getMixFormat =
                Marshal.GetDelegateForFunctionPointer<AudioClientGetMixFormatDelegate>(pfnGetMixFormat);

            int hrMix = getMixFormat(pAudioClient, out pMixFormat);
            if (hrMix < 0 || pMixFormat == IntPtr.Zero)
            {
                return 48000;
            }

            // WAVEFORMATEX::nSamplesPerSec is uint32 at byte offset +4
            int sampleRate = Marshal.ReadInt32(pMixFormat, 4);
            Trace.WriteLine($"[SpatialAudio] Probed Windows default output mix format sample rate: {sampleRate} Hz");
            return sampleRate == 44100 ? 44100 : 48000;
        }
        catch (Exception ex)
        {
            Trace.WriteLine($"[SpatialAudio] Default output sample-rate probe fallback (48000 Hz): {ex.Message}");
            return 48000;
        }
        finally
        {
            if (pMixFormat != IntPtr.Zero)
            {
                Marshal.FreeCoTaskMem(pMixFormat);
            }
            ReleaseComObject(pAudioClient);
            ReleaseComObject(pDevice);
            ReleaseComObject(pEnumerator);
            if (comInitialized)
            {
                CoUninitialize();
            }
        }
    }

    private static void ReleaseComObject(IntPtr pUnk)
    {
        if (pUnk == IntPtr.Zero)
        {
            return;
        }

        try
        {
            IntPtr vtbl = Marshal.ReadIntPtr(pUnk);
            IntPtr pfnRelease = Marshal.ReadIntPtr(vtbl, 2 * IntPtr.Size);
            ComReleaseDelegate release = Marshal.GetDelegateForFunctionPointer<ComReleaseDelegate>(pfnRelease);
            release(pUnk);
        }
        catch
        {
            // Safe COM cleanup guard
        }
    }

    /// <summary>
    ///     Negotiates K2 <c>sound_mixRate</c> (<c>44100</c> vs <c>48000</c>) and <c>sound_bufferLength</c>
    ///     (<c>100</c> ms for native FMOD stereo vs <c>256</c> ms for OpenAL Soft HRTF).
    /// </summary>
    public static (string MixRate, string BufferLength) ResolveAudioCvars(
        bool enableSpatialAudio,
        int? endpointSampleRateOverride = null)
    {
        int negotiatedHz = ProbeDefaultOutputEndpointSampleRate(endpointSampleRateOverride);
        string mixRate = negotiatedHz == 44100 ? "44100" : "48000";
        string bufferLength = enableSpatialAudio ? "256" : "100";
        return (mixRate, bufferLength);
    }

    /// <summary>
    ///     Generates low-latency, spatial-optimized K2 engine audio configuration cvars.
    /// </summary>
    public string GenerateK2AudioConfig(
        bool enableSpatialAudio,
        bool enableOcclusionDamping = true,
        int numChannels = 128,
        int mixRate = 48000)
    {
        string occlusionValue = enableOcclusionDamping ? "true" : "false";
        string bufferLength = enableSpatialAudio ? "256" : "100";

        StringBuilder sb = new();
        sb.AppendLine("// Spatial Audio Modernization & Low-Latency Engine Tuning");
        sb.AppendLine($"SetSave \"sound_numChannels\" \"{numChannels}\"");
        sb.AppendLine($"SetSave \"sound_bufferLength\" \"{bufferLength}\"");
        sb.AppendLine($"SetSave \"sound_mixRate\" \"{mixRate}\"");
        sb.AppendLine($"SetSave \"sound_recording_mixRate\" \"{mixRate}\"");
        sb.AppendLine("SetSave \"sound_distanceFactor\" \"1.0000\"");
        sb.AppendLine("SetSave \"sound_dopplerFactor\" \"1.0000\"");
        sb.AppendLine($"SetSave \"sound_geometryOcclusion\" \"{occlusionValue}\"");
        sb.AppendLine("SetSave \"sound_customRolloff\" \"true\"");
        sb.AppendLine("SetSave \"sound_rolloffScale\" \"1.0000\"");
        sb.AppendLine("SetSave \"sound_speakerModeStereo\" \"true\"");
        sb.AppendLine("SetSave \"sound_speakerModeMono\" \"false\"");
        sb.AppendLine("SetSave \"sound_prologic\" \"false\"");
        sb.AppendLine("SetSave \"sound_resampler\" \"2\"");
        sb.AppendLine("SetSave \"sound_useCompressedSamples\" \"true\"");

        return sb.ToString();
    }

    /// <summary>
    ///     Transforms K2 engine world coordinates (+X right, +Y forward, +Z up)
    ///     to OpenAL Soft listener/source coordinates (+X right, +Y up, -Z forward).
    /// </summary>
    public static (float X, float Y, float Z) ConvertK2ToOpenAlCoordinates(float k2X, float k2Y, float k2Z)
    {
        // K2: X=Right, Y=Forward, Z=Up
        // OpenAL: X=Right, Y=Up, Z=-Forward (Backwards)
        return (k2X, k2Z, -k2Y);
    }

    /// <summary>
    ///     Transforms K2 engine camera orientation vectors to OpenAL 6-float listener orientation.
    /// </summary>
    public static (float FwdX, float FwdY, float FwdZ, float UpX, float UpY, float UpZ) ConvertK2ListenerOrientation(
        float k2FwdX, float k2FwdY, float k2FwdZ,
        float k2UpX, float k2UpY, float k2UpZ)
    {
        (float fwdX, float fwdY, float fwdZ) = ConvertK2ToOpenAlCoordinates(k2FwdX, k2FwdY, k2FwdZ);
        (float upX, float upY, float upZ) = ConvertK2ToOpenAlCoordinates(k2UpX, k2UpY, k2UpZ);
        return (fwdX, fwdY, fwdZ, upX, upY, upZ);
    }

    /// <summary>
    ///     Applies the complete spatial audio deployment to the client directory: writes <c>alsoft.ini</c>,
    ///     ensures HRTF folders exist, and prepares proxy binaries.
    /// </summary>
    public void ApplyAudioModernization(
        string clientDirectory,
        bool enableSpatialAudio,
        string hrtfProfile,
        bool enableOcclusionDamping = true,
        int channels = 128,
        int? endpointSampleRateOverride = null)
    {
        if (string.IsNullOrWhiteSpace(clientDirectory) || !Directory.Exists(clientDirectory))
        {
            _logger.LogWarning("[SpatialAudio] Invalid client directory: {Dir}", clientDirectory);
            return;
        }

        try
        {
            // 1. Ensure local ./hrtf/ folder exists
            string localHrtf = Path.Combine(clientDirectory, HrtfSubdirectory);
            if (!Directory.Exists(localHrtf))
            {
                Directory.CreateDirectory(localHrtf);
                _logger.LogInformation("[SpatialAudio] Initialized HRTF directory at {Path}", localHrtf);
            }

            // 2. Ensure %APPDATA%/ProjectKongor/hrtf/ exists
            string userHrtf = Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData),
                "ProjectKongor",
                HrtfSubdirectory);
            if (!Directory.Exists(userHrtf))
            {
                Directory.CreateDirectory(userHrtf);
            }

            // 3. Write alsoft.ini with negotiated output sample rate
            int negotiatedFrequency = ProbeDefaultOutputEndpointSampleRate(endpointSampleRateOverride);
            string configContent = GenerateAlsoftConfig(
                enableSpatialAudio,
                hrtfProfile,
                enableOcclusionDamping,
                negotiatedFrequency,
                localHrtf);

            string configPath = Path.Combine(clientDirectory, AlsoftConfigFileName);
            File.WriteAllText(configPath, configContent);
            _logger.LogInformation(
                "[SpatialAudio] Applied OpenAL Soft configuration to {Path} (HRTF: {Enabled}, Profile: {Profile}, SampleRate: {Hz} Hz)",
                configPath,
                enableSpatialAudio,
                hrtfProfile,
                negotiatedFrequency);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "[SpatialAudio] Failed to apply spatial audio configuration to {Dir}", clientDirectory);
        }
    }

