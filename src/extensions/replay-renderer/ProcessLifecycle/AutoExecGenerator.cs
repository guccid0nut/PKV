using System.Text;
using ReplayRenderer.Service.Models;

namespace ReplayRenderer.Service.ProcessLifecycle;

/// <summary>
///     Generates deterministic autoexec.cfg configuration scripts for automated HoN replay sessions.
/// </summary>
public static class AutoExecGenerator
{
    /// <summary>
    ///     Generates the complete autoexec.cfg text based on the provided render job configuration and replay file name.
    /// </summary>
    public static string Generate(RenderJobConfiguration config, string replayFileName)
    {
        ArgumentNullException.ThrowIfNull(config);
        ArgumentException.ThrowIfNullOrWhiteSpace(replayFileName);

        string uiSetting = config.EnableCleanCinematicUi ? "false" : "true";

        StringBuilder sb = new();
        sb.AppendLine("// ==========================================================");
        sb.AppendLine("// autoexec.cfg auto-generated by NEXUS Replay Renderer");
        sb.AppendLine("// ==========================================================");
        sb.AppendLine("// 1. Deterministic Frame Clock & Display Settings");
        sb.AppendLine("Set \"host_vidDriver\" \"vid_d3d9\"");
        sb.AppendLine("Set \"vid_driver\" \"d3d9\"");
        sb.AppendLine($"Set \"vid_resolution\" \"{config.RenderWidth},{config.RenderHeight}\"");
        sb.AppendLine("Set \"vid_fullscreen\" \"false\"");
        sb.AppendLine("Set \"vid_borderless\" \"true\"");
        sb.AppendLine("SetSave \"vid_fullscreen\" \"false\"");
        sb.AppendLine("SetSave \"vid_borderless\" \"true\"");
        sb.AppendLine($"SetSave \"vid_resolution\" \"{config.RenderWidth},{config.RenderHeight}\"");
        if (config.Headless)
        {
            sb.AppendLine("Set \"vid_pos\" \"-32000,-32000\"");
            sb.AppendLine("SetSave \"vid_pos\" \"-32000,-32000\"");
        }
        sb.AppendLine("Set \"vid_bpp\" \"32\"");
        sb.AppendLine("Set \"vid_refreshRate\" \"60\"");
        sb.AppendLine("Set \"sys_fixedFrameTime\" \"0\"");
        sb.AppendLine($"Set \"host_framerate\" \"{config.TargetFramerate}\"");
        sb.AppendLine($"Set \"host_timescale\" \"{config.Timescale:F4}\"");
        sb.AppendLine("Set \"sys_sleepTime\" \"0\"");
        sb.AppendLine($"Set \"vid_maxFPS\" \"{config.TargetFramerate}\"");
        sb.AppendLine($"Set \"cl_maxFPS\" \"{config.TargetFramerate}\"");
        sb.AppendLine($"Set \"host_maxFPS\" \"{config.TargetFramerate}\"");
        sb.AppendLine("Set \"vid_vsync\" \"false\"");
        sb.AppendLine("Set \"gl_swapInterval\" \"0\"");
        sb.AppendLine("Set \"d3d_tripleBuffering\" \"false\"");
        sb.AppendLine("Set \"d3d_pure\" \"false\"");
        sb.AppendLine("Set \"sys_pauseOnUnfocus\" \"false\"");
        sb.AppendLine("Set \"vid_pauseOnUnfocus\" \"false\"");
        sb.AppendLine("Set \"cl_pauseOnUnfocus\" \"false\"");
        sb.AppendLine("Set \"sys_unfocusedSleep\" \"0\"");
        sb.AppendLine("Set \"net_smoothInterpolation\" \"1\"");
        sb.AppendLine("Set \"cl_packetEpsilon\" \"0.001\"");
        sb.AppendLine();
        sb.AppendLine("// 2. Ultra Graphics Quality Profile");
        sb.AppendLine("Set \"vid_shadows\" \"true\"");
        sb.AppendLine("Set \"vid_terrainShadows\" \"true\"");
        sb.AppendLine("Set \"vid_shadowmapSize\" \"2048\"");
        sb.AppendLine("Set \"vid_shadowmapFilterWidth\" \"2\"");
        sb.AppendLine("Set \"vid_shadowmapType\" \"0\"");
        sb.AppendLine("Set \"vid_shadowDrawDistance\" \"3000.0000\"");
        sb.AppendLine("Set \"vid_shadowFalloffDistance\" \"1000.0000\"");
        sb.AppendLine("Set \"vid_shadowLeak\" \"0.0500\"");
        sb.AppendLine("Set \"vid_dynamicLights\" \"true\"");
        sb.AppendLine("Set \"vid_maxDynamicLights\" \"4\"");
        sb.AppendLine("Set \"vid_sceneDynamicLights\" \"true\"");
        sb.AppendLine("Set \"vid_meshQuality\" \"0\"");
        sb.AppendLine("Set \"vid_textureFiltering\" \"3\"");
        sb.AppendLine("Set \"vid_textureCompression\" \"true\"");
        sb.AppendLine("Set \"vid_textureDownsize\" \"0\"");
        sb.AppendLine("Set \"vid_modelLOD\" \"0\"");
        sb.AppendLine("Set \"vid_shaderLightingQuality\" \"0\"");
        sb.AppendLine("Set \"vid_shaderWaterQuality\" \"0\"");
        sb.AppendLine("Set \"vid_shaderAmbientOcclusion\" \"true\"");
        sb.AppendLine("Set \"vid_shaderRimLighting\" \"true\"");
        sb.AppendLine("Set \"vid_reflectionMapSize\" \"2048\"");
        sb.AppendLine("Set \"vid_treeSmoothNormals\" \"true\"");
        sb.AppendLine("Set \"vid_foliageFalloffDistance\" \"1200.0000\"");
        sb.AppendLine("Set \"vid_antialiasing\" \"4\"");
        sb.AppendLine("Set \"vid_reflections\" \"true\"");
        sb.AppendLine("Set \"vid_postEffects\" \"false\"");
        sb.AppendLine("Set \"replay_playback_speed\" \"1.0\"");
        sb.AppendLine("Set \"replay_auto_quit\" \"false\"");
        sb.AppendLine("Set \"con_log\" \"1\"");
        sb.AppendLine("Set \"host_writeConsole\" \"true\"");
        sb.AppendLine();
        sb.AppendLine("// 3. UI & HUD Suppression Settings");
        sb.AppendLine("Set \"ui_render\" \"true\"");
        sb.AppendLine($"Set \"cg_draw2d\" \"{uiSetting}\"");
        sb.AppendLine($"Set \"cg_drawHealthBars\" \"{uiSetting}\"");
        sb.AppendLine($"Set \"cg_drawUnitFrames\" \"{uiSetting}\"");
        sb.AppendLine($"Set \"cg_drawMinimap\" \"{uiSetting}\"");
        sb.AppendLine($"Set \"cg_drawChat\" \"{uiSetting}\"");
        sb.AppendLine("Set \"cg_drawFPS\" \"false\"");
        sb.AppendLine("Set \"con_notify\" \"false\"");
        sb.AppendLine("Set \"ui_showQuickStart\" \"false\"");
        sb.AppendLine("Set \"cg_enableLoginAnimation\" \"false\"");
        sb.AppendLine("Set \"ui_suppressAutoLogin\" \"true\"");
        sb.AppendLine("Set \"login_autoLogin\" \"false\"");
        sb.AppendLine("Set \"login_rememberPassword\" \"false\"");
        sb.AppendLine("Set \"cl_reconnectAttempts\" \"0\"");
        sb.AppendLine("Set \"svr_port\" \"11299\"");
        sb.AppendLine("SetSave \"svr_port\" \"11299\"");
        sb.AppendLine();
        sb.AppendLine("// 4. Replay POV & Camera Synchronization");
        sb.AppendLine($"Set \"replay_target\" \"replays/{replayFileName}\"");
        sb.AppendLine($"Set \"replay_client\" \"{config.PovClientIndex}\"");
        sb.AppendLine("Set \"cg_lockCamera\" \"true\"");
        sb.AppendLine("Set \"cg_fogofwar\" \"true\"");
        sb.AppendLine("Set \"cam_mode\" \"0\"");
        sb.AppendLine("Set \"cam_smooth\" \"1\"");
        sb.AppendLine("Set \"cg_cameraSmoothing\" \"1\"");
        sb.AppendLine($"Set \"host_autoexec\" \"StartReplay replays/{replayFileName}\"");

        return sb.ToString();
    }
}
